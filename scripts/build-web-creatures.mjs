#!/usr/bin/env node
// Builds the compressed runtime creature models (0.66.0).
//
// The authoring sources live outside the deploy: art/creatures/*.glb and the anatomy rigs in art/rigs
// (whose .gltf files point into those GLBs byte for byte). Tests and the rig/animation scripts read the sources.
// The game loads one self-contained file per Level instead, built here from exactly the asset it loaded before
// (creatureAsset in world-layout.js, rig or source GLB):
//   1. copy        resolve the rig's external buffers into one GLB
//   2. resize      base-colour texture 2048 → 1024 px (Lanczos)
//   3. etc1s       KTX2 / Basis Universal ETC1S texture (KHR_texture_basisu): GPU-compressed in memory
//   4. meshopt     EXT_meshopt_compression + KHR_mesh_quantization geometry and animation (always last)
// Root extras (maximaLocomotion, maximaRig, ravenclawWalkV2), animation, node and bone names are kept; the script
// checks them. Output: dist/assets/creatures-web/<id>-<level>.<hash>.glb and dist/creature-web-assets.js (the map).
//
// Needs, outside the repository: @gltf-transform/cli 4.x (npm) and KTX-Software 4.x `toktx` on PATH
// (https://github.com/KhronosGroup/KTX-Software/releases). Then: npm run creatures:web && npm run offline
import fs from 'node:fs';import path from 'node:path';import os from 'node:os';import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';import {fileURLToPath} from 'node:url';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),DIST=path.join(ROOT,'dist'),OUT=path.join(DIST,'assets/creatures-web');
const {creatureAsset}=await import(path.join(ROOT,'src','world-layout.js'));
const PARTNERS=['gryffindor','hufflepuff','ravenclaw','slytherin'],LEVELS=[...Array(11).keys()];
const TEXTURE=Number(process.env.CREATURE_TEXTURE||1024),QUALITY=String(process.env.CREATURE_ETC1S_QUALITY||255);
const cli=process.env.GLTF_TRANSFORM||'gltf-transform';
const run=(...args)=>execFileSync(cli,args,{stdio:['ignore','ignore','pipe']});
function readJSON(file){const b=fs.readFileSync(file);if(file.endsWith('.gltf'))return JSON.parse(b);const n=b.readUInt32LE(12);return JSON.parse(b.subarray(20,20+n));}
const pick=j=>({extras:j.extras||null,animations:(j.animations||[]).map(a=>a.name).sort(),nodes:(j.nodes||[]).map(n=>n.name||'').filter(Boolean).sort()});
fs.mkdirSync(OUT,{recursive:true});
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'creatures-web-')),map={},report=[];
for(const id of PARTNERS)for(const level of LEVELS){
 const asset=creatureAsset(level,id).split('?')[0],src=path.join(ROOT,'art',asset),key=`${id}-${level}`,t=n=>path.join(tmp,`${key}-${n}.glb`);
 run('copy',src,t('a'));run('resize',t('a'),t('b'),'--width',String(TEXTURE),'--height',String(TEXTURE));
 run('etc1s',t('b'),t('c'),'--quality',QUALITY);run('meshopt',t('c'),t('d'));
 const before=pick(readJSON(src)),after=readJSON(t('d'));
 if(JSON.stringify(before)!==JSON.stringify(pick(after)))throw Error(`${key}: extras, animation or node names changed`);
 for(const ext of['EXT_meshopt_compression','KHR_texture_basisu'])if(!after.extensionsUsed?.includes(ext))throw Error(`${key}: missing ${ext}`);
 const data=fs.readFileSync(t('d')),hash=crypto.createHash('sha256').update(data).digest('hex').slice(0,10),name=`${key}.${hash}.glb`;
 fs.writeFileSync(path.join(OUT,name),data);map[key]=`assets/creatures-web/${name}`;
 const sourceBytes=asset.endsWith('.gltf')?readJSON(src).buffers.reduce((n,b)=>n+fs.statSync(path.join(path.dirname(src),b.uri)).size,fs.statSync(src).size):fs.statSync(src).size;
 report.push({key,source:asset,sourceBytes,bytes:data.length});process.stdout.write(`${key} ${Math.round(sourceBytes/1024)} KB → ${Math.round(data.length/1024)} KB\n`);
}
fs.rmSync(tmp,{recursive:true,force:true});
const keep=new Set(Object.values(map).map(f=>path.basename(f)));for(const f of fs.readdirSync(OUT))if(!keep.has(f))fs.rmSync(path.join(OUT,f));
fs.writeFileSync(path.join(ROOT,'src','creature-web-assets.js'),`// Generated by scripts/build-web-creatures.mjs: compressed runtime creature models (meshopt geometry, KTX2 ${TEXTURE} px textures).\nexport const CREATURE_WEB=${JSON.stringify(map,null,1)};\n`);
const total=k=>report.reduce((n,r)=>n+r[k],0);
fs.writeFileSync(path.join(ROOT,'docs/audits/CREATURE-COMPRESSION.json'),JSON.stringify({texture:TEXTURE,etc1sQuality:Number(QUALITY),sourceBytes:total('sourceBytes'),runtimeBytes:total('bytes'),forms:report},null,1)+'\n');
console.log(`44 forms: ${(total('sourceBytes')/1048576).toFixed(1)} MB → ${(total('bytes')/1048576).toFixed(1)} MB`);
